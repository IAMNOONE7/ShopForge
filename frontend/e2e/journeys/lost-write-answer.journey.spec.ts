import { test, expect, type LostWriteAnswer } from "../support/isolatedFixtures.ts";
import { registerShopper } from "../support/registeredShopper.ts";
import { addVariant, cartReading, checkout, downloadOrderDocument, expectReceipt, fillCheckout, labels, money, noOverflow, submitCheckout } from "../support/shopper.ts";
import type { Page } from "@playwright/test";

function expectReplay(loss: LostWriteAnswer) {
  expect(loss.committed).not.toBeNull();
  expect(loss.requests).toHaveLength(2);
  expect(loss.requests[0].key).toBeTruthy();
  expect(loss.requests[1]).toEqual(loss.requests[0]);
}

async function accountOrders(page: Page) {
  return page.evaluate(async () => {
    const response = await fetch("/api/storefront/account/orders", { credentials: "same-origin" });
    if (!response.ok) throw new Error(`Account history returned ${response.status}`);
    return await response.json() as { number: string; status: string; grandTotal: number; items: number }[];
  });
}

test("lost checkout answer recovers the committed order with an explicit identical request", async ({ page, context, runSession, writeTransport }, testInfo) => {
  const store = runSession.run.stores[0], origin = runSession.origin(store), words = labels(testInfo);
  const shopper = await registerShopper(page, runSession, store, testInfo);
  const product = runSession.run.products.find(product => product.variants.some(variant => variant.size === "S"))!;
  const variant = product.variants.find(variant => variant.size === "S")!;
  await addVariant(page, runSession, store, product, variant, testInfo);
  await fillCheckout(page, runSession, store, product);
  const cookiesBefore = await context.cookies(origin);
  expect(cookiesBefore.some(cookie => cookie.name === "shopforge_cart")).toBe(true);
  expect(() => writeTransport.loseNextAnswer(`${runSession.environment.rigOrigin}/api/storefront/checkout`)).toThrow("this run's checkout or return request");
  const loss = writeTransport.loseNextAnswer(`${origin}/api/storefront/checkout`);
  await page.getByRole("button", { name: words.checkout.placeOrder, exact: true }).click();
  await expect(page.getByText(words.checkout.sameRequestRetry, { exact: true })).toBeVisible();
  await expect(page).toHaveURL(`${origin}/checkout`);
  expect(loss.committed?.status).toBe(201);
  expect(await context.cookies(origin), "An undelivered response must not delete the browser's cart cookie").toEqual(cookiesBefore);
  const committed = loss.committed!.body as { number: string; redirectUrl: string };
  expect(await accountOrders(page)).toEqual([expect.objectContaining({ number: committed.number, status: "AwaitingPayment", grandTotal: product.price, items: 1 })]);
  expect((await cartReading(page)).items).toEqual([]);
  const before = await runSession.order(store, committed.number);
  expect(before.order).toMatchObject({ status: "AwaitingPayment", email: shopper.email, paidAt: null });
  expect(before.attempts).toEqual([expect.objectContaining({ provider: "comgate", status: "Started", environment: null })]);
  expect(before.documents).toEqual([]); expect(before.answersRecorded).toBe(0);
  expect(await runSession.stock(variant.sku)).toEqual({ sku: variant.sku, onHand: variant.stock, reserved: 1, available: variant.stock - 1 });
  const gatewayBefore = await runSession.gateway();
  expect(gatewayBefore.transactions).toHaveLength(1);
  expect(gatewayBefore.transactions[0]).toMatchObject({ referenceId: committed.number, status: "PENDING", price: product.price * 100, refunded: 0 });

  const submit = page.getByRole("button", { name: words.checkout.placeOrder, exact: true });
  const phone = page.locator('input[name="phone"]');
  await phone.fill("+420 777 123 457");
  await expect(page.locator(".checkout-review")).toContainText(words.checkout.uncertainChangedTitle);
  await expect(submit).toBeDisabled();
  await phone.press("Enter");
  expect(loss.requests).toHaveLength(1);
  await phone.fill("+420 777 123 456");
  await expect(page.getByText(words.checkout.sameRequestRetry, { exact: true })).toBeVisible();
  await expect(submit).toBeEnabled();
  await noOverflow(page);
  await testInfo.attach("checkout-answer-lost", { body: await page.screenshot({ fullPage: true }), contentType: "image/png" });
  expect(loss.requests).toHaveLength(1);

  const placed = await submitCheckout(page, runSession, store, product, testInfo);
  expect(placed.replayed).toBe(true); expect(placed.number).toBe(committed.number);
  expect(page.url()).toBe(committed.redirectUrl);
  expectReplay(loss);
  expect(await runSession.gateway()).toEqual(gatewayBefore);
  expect(await runSession.stock(variant.sku)).toEqual({ sku: variant.sku, onHand: variant.stock, reserved: 1, available: variant.stock - 1 });
  await page.getByRole("button", { name: "Pay", exact: true }).click();
  await expectReceipt(page, origin, placed.number);
  await expect(page.locator(".order-status.paid")).toHaveText(words.orders.status.Paid);
  await expect(page.locator(".order-grand-total dd")).toHaveText(money(product.price));
  await expect.poll(async () => (await runSession.order(store, placed.number)).documents.length).toBe(1);
  const paid = await runSession.order(store, placed.number);
  expect(paid.order).toMatchObject({ status: "Paid", paymentReference: placed.transactionId, refundedTotal: 0 });
  expect(paid.lines).toEqual([{ productName: `${product.name} (${variant.size})`, variantId: variant.id, quantity: 1, unitPrice: product.price, discount: 0 }]);
  expect(paid.attempts).toEqual([expect.objectContaining({ reference: placed.transactionId, status: "Paid", amount: product.price, currency: "CZK", environment: "test" })]);
  expect(paid.answersRecorded).toBe(1); expect(paid.kept).toEqual([]); expect(paid.returns).toEqual([]);
  expect(paid.documents).toEqual([expect.objectContaining({ kind: "Invoice" })]);
  for (const form of product.variants) expect(await runSession.stock(form.sku)).toEqual({ sku: form.sku, onHand: form.stock - (form.id === variant.id ? 1 : 0), reserved: 0, available: form.stock - (form.id === variant.id ? 1 : 0) });
  await downloadOrderDocument(page, paid.documents[0].number, testInfo);
  for (const prefix of ["Your order", "Payment received for order"]) await expect.poll(async () => (await runSession.mail(shopper.email)).filter(letter => letter.subject === `${store.name}: ${prefix} ${placed.number}`).length).toBe(1);
  await page.goto(`${origin}/account`);
  await expect(page.locator(".account-order-list > li")).toHaveCount(1);
  await expect(page.locator(".account-order-list")).toContainText(placed.number);
  expect(await accountOrders(page)).toEqual([expect.objectContaining({ number: placed.number, status: "Paid", grandTotal: product.price, items: 1 })]);
  expect((await runSession.gateway()).transactions).toHaveLength(1);
  expectReplay(loss);
  await noOverflow(page);
  await testInfo.attach("checkout-recovered-once", { body: await page.screenshot({ fullPage: true }), contentType: "image/png" });
  await testInfo.attach("lost-checkout-facts", { body: JSON.stringify({ before, paid, gateway: await runSession.gateway(), stock: await runSession.stock(variant.sku), requests: loss.requests }), contentType: "application/json" });
});

test("lost return answer replays one request and credits the purchased variant once", async ({ page, runSession, writeTransport }, testInfo) => {
  const store = runSession.run.stores[0], origin = runSession.origin(store), words = labels(testInfo);
  const shopper = await registerShopper(page, runSession, store, testInfo);
  const product = runSession.run.products.find(product => product.variants.some(variant => variant.size === "L"))!;
  const variant = product.variants.find(variant => variant.size === "L")!, savedName = `${product.name} (${variant.size})`;
  await addVariant(page, runSession, store, product, variant, testInfo);
  const placed = await checkout(page, runSession, store, product, testInfo);
  await page.getByRole("button", { name: "Pay", exact: true }).click();
  await expectReceipt(page, origin, placed.number);
  await expect(page.locator(".order-status.paid")).toHaveText(words.orders.status.Paid);
  await page.goto(`${origin}/account/orders/${placed.number}`);
  await page.getByRole("combobox", { name: words.orders.returnQuantity.replace("{{name}}", savedName), exact: true }).selectOption("1");
  const reason = "Velikost mi nesedí / The size does not fit";
  const reasonField = page.getByRole("textbox", { name: words.orders.returnReason, exact: true });
  await reasonField.fill(reason);
  const target = `${origin}/api/storefront/account/orders/${placed.number}/returns`;
  const loss = writeTransport.loseNextAnswer(target);
  const submit = page.getByRole("button", { name: words.orders.returnAsk, exact: true });
  await submit.click();
  await expect(page.getByText(words.orders.returnSameRequestRetry, { exact: true })).toBeVisible();
  expect(loss.committed?.status).toBe(200);
  const committed = loss.committed!.body as { returnable: unknown[]; returns: { number: string; status: string }[] };
  expect(committed.returnable).toEqual([]); expect(committed.returns).toHaveLength(1);
  const returned = committed.returns[0];
  expect(returned.status).toBe("Requested");
  const before = await runSession.order(store, placed.number);
  expect(before.returns).toEqual([expect.objectContaining({ number: returned.number, status: "Requested" })]);
  expect(before.documents.filter(document => document.kind === "CreditNote")).toEqual([]);
  expect(await runSession.stock(variant.sku)).toEqual({ sku: variant.sku, onHand: variant.stock - 1, reserved: 0, available: variant.stock - 1 });
  await reasonField.fill(`${reason} — changed`);
  await expect(page.locator(".return-review")).toContainText(words.orders.returnChangedTitle);
  await expect(submit).toBeDisabled();
  expect(loss.requests).toHaveLength(1);
  await reasonField.fill(reason);
  await expect(page.getByText(words.orders.returnSameRequestRetry, { exact: true })).toBeVisible();
  await expect(submit).toBeEnabled();
  await noOverflow(page);
  await testInfo.attach("return-answer-lost", { body: await page.screenshot({ fullPage: true }), contentType: "image/png" });
  expect(loss.requests).toHaveLength(1);

  const response = page.waitForResponse(answer => answer.url() === target && answer.request().method() === "POST");
  await submit.click();
  const replay = await response;
  expect(replay.status()).toBe(200); expect(replay.headers()["idempotent-replay"]).toBe("true");
  expect(await replay.json()).toEqual(committed);
  expectReplay(loss);
  expect(JSON.parse(loss.requests[0].body!)).toEqual({ lines: [{ storeProductId: product.listings[store.id], variantId: variant.id, quantity: 1 }], reason });
  await expect(page.locator(".return-list > li")).toHaveCount(1);
  await expect(page.locator(".return-list")).toContainText(returned.number);
  await expect(page.locator(".return-list .return-handling-status")).toHaveText(words.orders.returnStatus.Requested);
  await expect(page.locator(".return-form")).toHaveCount(0);
  expect((await runSession.order(store, placed.number)).returns).toEqual(before.returns);
  await runSession.advanceReturn(store, placed.number, returned.number, "accept");
  const received = await runSession.advanceReturn(store, placed.number, returned.number, "receive");
  expect(received).toMatchObject({ refund: "Refunded", refundedAmount: product.price, refundProblem: null });
  await expect.poll(async () => (await runSession.order(store, placed.number)).documents.filter(document => document.kind === "CreditNote").length).toBe(1);
  const credited = await runSession.order(store, placed.number);
  expect(credited.order).toMatchObject({ status: "Refunded", refundedTotal: product.price, paymentReference: placed.transactionId });
  expect(credited.lines).toEqual([{ productName: savedName, variantId: variant.id, quantity: 1, unitPrice: product.price, discount: 0 }]);
  expect(credited.returns).toEqual([{ number: returned.number, status: "Received", refundStatus: "Refunded", refundedAmount: product.price, refundProblem: null }]);
  expect(credited.attempts).toEqual([expect.objectContaining({ status: "Paid", reference: placed.transactionId, amount: product.price })]);
  expect(credited.answersRecorded).toBe(1); expect(credited.kept).toEqual([]);
  expect(credited.documents.filter(document => document.kind === "Invoice")).toHaveLength(1);
  expect(credited.documents).toHaveLength(2);
  const gateway = await runSession.gateway();
  expect(gateway.transactions).toHaveLength(1);
  expect(gateway.transactions[0]).toMatchObject({ id: placed.transactionId, refunded: product.price * 100 });
  for (const form of product.variants) expect(await runSession.stock(form.sku)).toEqual({ sku: form.sku, onHand: form.stock, reserved: 0, available: form.stock });
  await page.reload();
  await expect(page.locator(".order-status.refunded")).toHaveText(words.orders.status.Refunded);
  await expect(page.locator(".return-list > li")).toHaveCount(1);
  await expect(page.locator(".return-list .return-handling-status")).toHaveText(words.orders.returnStatus.Received.replace("{{amount}}", money(product.price)));
  await downloadOrderDocument(page, credited.documents.find(document => document.kind === "CreditNote")!.number, testInfo);
  for (const subject of [`Return ${returned.number} for order ${placed.number}`, `Refund for order ${placed.number}`]) await expect.poll(async () => (await runSession.mail(shopper.email)).filter(letter => letter.subject === `${store.name}: ${subject}`).length).toBe(1);
  expect(await accountOrders(page)).toEqual([expect.objectContaining({ number: placed.number, status: "Refunded", grandTotal: product.price, items: 1 })]);
  expectReplay(loss);
  await noOverflow(page);
  await testInfo.attach("return-recovered-once", { body: await page.screenshot({ fullPage: true }), contentType: "image/png" });
  await testInfo.attach("lost-return-facts", { body: JSON.stringify({ before, credited, gateway, stock: await runSession.stock(variant.sku), requests: loss.requests }), contentType: "application/json" });
});
